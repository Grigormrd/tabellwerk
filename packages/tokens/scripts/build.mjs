// Builds the token outputs from the DTCG sources in ../tokens:
//   dist/tokens.css  CSS custom properties for light, dark and forced-colors
//   dist/index.js    typed references (`var(--tbw-…)`) and the resolved values per theme
//   dist/index.d.ts  literal types for both
//
// Style Dictionary resolves references and applies the CSS transforms; the
// file layout (cascade layer, theme selectors, media queries) is written here,
// because one token set has to end up in several selectors.

import { mkdir, rm, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import StyleDictionary from "style-dictionary";

const root = fileURLToPath(new URL("..", import.meta.url));
const dist = `${root}dist/`;

export const PREFIX = "tbw";
export const THEME_ATTRIBUTE = "data-tbw-theme";

/**
 * In forced-colors mode (Windows contrast themes) the browser replaces colours
 * with system colours anyway; mapping the roles explicitly keeps custom
 * backgrounds and borders that the browser would not touch (for example
 * colours used in `box-shadow` or `outline`) in line with the user's theme.
 */
const FORCED_COLORS = {
  bg: "Canvas",
  surface: "Canvas",
  "surface-hover": "Canvas",
  text: "CanvasText",
  "text-muted": "CanvasText",
  border: "GrayText",
  "border-strong": "CanvasText",
  accent: "Highlight",
  "accent-text": "HighlightText",
  "accent-subtle": "Canvas",
  focus: "Highlight",
  danger: "CanvasText",
};

async function resolve(sources) {
  const sd = new StyleDictionary(
    {
      source: sources.map((file) => `${root}tokens/${file}`),
      log: { verbosity: "silent", warnings: "error" },
      platforms: {
        css: { transformGroup: "css", prefix: PREFIX },
      },
    },
    { verbosity: "silent" },
  );
  await sd.hasInitialized;
  const { allTokens } = await sd.getPlatformTokens("css");
  return allTokens;
}

function declarations(tokens, indent) {
  return tokens
    .map((token) => `${indent}--${token.name}: ${token.$value ?? token.value};`)
    .join("\n");
}

function setPath(target, path, value) {
  let node = target;
  for (const key of path.slice(0, -1)) node = node[key] ??= {};
  node[path.at(-1)] = value;
}

function typeLiteral(value, indent = "") {
  if (typeof value === "string") return JSON.stringify(value);
  const inner = `${indent}  `;
  const entries = Object.entries(value).map(
    ([key, child]) => `${inner}readonly ${JSON.stringify(key)}: ${typeLiteral(child, inner)};`,
  );
  return `{\n${entries.join("\n")}\n${indent}}`;
}

const base = await resolve(["base.json"]);
const light = await resolve(["color.light.json"]);
const dark = await resolve(["color.dark.json"]);

const lightNames = light.map((t) => t.name).join();
const darkNames = dark.map((t) => t.name).join();
if (lightNames !== darkNames) {
  throw new Error(
    "color.light.json and color.dark.json must define the same tokens in the same order",
  );
}
for (const token of light) {
  const role = token.path.slice(1).join("-");
  if (!(role in FORCED_COLORS))
    throw new Error(`No forced-colors mapping for color role "${role}"`);
}

const forced = light.map((token) => ({
  name: token.name,
  $value: FORCED_COLORS[token.path.slice(1).join("-")],
}));

const css = `/* @tabellwerk/tokens: generated by scripts/build.mjs, do not edit. */
@layer tabellwerk.tokens {
  :root,
  [${THEME_ATTRIBUTE}="light"] {
${declarations(base, "    ")}
${declarations(light, "    ")}
  }

  @media (prefers-color-scheme: dark) {
    :root:not([${THEME_ATTRIBUTE}="light"]) {
${declarations(dark, "      ")}
    }
  }

  [${THEME_ATTRIBUTE}="dark"] {
${declarations(dark, "    ")}
  }

  @media (forced-colors: active) {
    :root,
    [${THEME_ATTRIBUTE}] {
${declarations(forced, "      ")}
    }
  }
}
`;

const vars = {};
for (const token of [...base, ...light]) setPath(vars, token.path, `var(--${token.name})`);

const valuesOf = (tokens) =>
  Object.fromEntries(tokens.map((t) => [t.path.slice(1).join("-"), String(t.$value ?? t.value)]));
const themes = { light: valuesOf(light), dark: valuesOf(dark) };

const js = `// @tabellwerk/tokens: generated by scripts/build.mjs, do not edit.
export const THEME_ATTRIBUTE = ${JSON.stringify(THEME_ATTRIBUTE)};
export const vars = ${JSON.stringify(vars, null, 2)};
export const themes = ${JSON.stringify(themes, null, 2)};
`;

const dts = `// @tabellwerk/tokens: generated by scripts/build.mjs, do not edit.
/** Attribute that forces a theme on an element and its descendants: \`light\` or \`dark\`. */
export declare const THEME_ATTRIBUTE: ${JSON.stringify(THEME_ATTRIBUTE)};
/** CSS \`var()\` references for every token, for use in inline styles or CSS-in-JS. */
export declare const vars: ${typeLiteral(vars)};
/** Resolved colour values per theme, keyed by colour role. */
export declare const themes: ${typeLiteral(themes)};
export type ColorRole = keyof typeof themes.light;
export type ThemeName = keyof typeof themes;
`;

await rm(dist, { recursive: true, force: true });
await mkdir(dist, { recursive: true });
await Promise.all([
  writeFile(`${dist}tokens.css`, css),
  writeFile(`${dist}index.js`, js),
  writeFile(`${dist}index.d.ts`, dts),
]);
console.log(`tokens: ${base.length + light.length} tokens, ${light.length} colour roles per theme`);
